import Foundation

public enum ReportExporter {
    // Locale-aware medium date + short time, matching the style ReportRow shows in-app
    // (.formatted(date: .abbreviated, time: .shortened)) — previously this was a fixed POSIX
    // "yyyy-MM-dd HH:mm:ss" format, so the same report's in-app timestamp and its exported
    // Markdown timestamp read as two unrelated formats.
    private static let df: DateFormatter = {
        let f = DateFormatter()
        f.dateStyle = .medium
        f.timeStyle = .short
        return f
    }()

    public static func markdown(_ r: ReconReport) -> String {
        var md = "# Recon report: \(r.target)\n\n"
        md += "- **Type:** \(r.kind)\n- **Started:** \(df.string(from: r.started))\n"
        if let f = r.finished { md += "- **Finished:** \(df.string(from: f))\n" }
        md += "- **Findings:** \(r.findings.count)\n\n"

        if !r.findings.isEmpty {
            md += "## Findings\n\n| Severity | Finding | Detail |\n|---|---|---|\n"
            for f in r.findings.sorted(by: { $0.severity > $1.severity }) {
                md += "| \(f.severity.rawValue.uppercased()) | \(esc(f.title)) | \(esc(f.detail)) |\n"
            }
            md += "\n"
        }
        for s in r.sections {
            md += "## \(s.title)\n\n"
            if let n = s.note { md += "_\(n)_\n\n" }
            for i in s.items {
                let mark = i.severity > .info ? " **[\(i.severity.rawValue)]**" : ""
                if i.label.isEmpty { md += "- \(i.value.replacingOccurrences(of: "\n", with: " "))\(mark)\n" }
                else if i.value.contains("\n") { md += "- **\(i.label):**\(mark)\n  ```\n  \(i.value.replacingOccurrences(of: "\n", with: "\n  "))\n  ```\n" }
                else { md += "- **\(i.label):** \(i.value)\(mark)\n" }
            }
            md += "\n"
        }
        md += "---\n_Generated by ReconKit. Only test systems you own or are authorised to assess._\n"
        return md
    }

    public static func json(_ r: ReconReport) -> Data? {
        let e = JSONEncoder()
        e.outputFormatting = [.prettyPrinted, .sortedKeys]
        e.dateEncodingStrategy = .iso8601
        return try? e.encode(r)
    }

    public static func plainText(sections: [ReportSection]) -> String {
        sections.map { s in
            "== \(s.title) ==\n" + s.items.map { $0.label.isEmpty ? $0.value : "\($0.label): \($0.value)" }.joined(separator: "\n")
        }.joined(separator: "\n\n")
    }

    private static func esc(_ s: String) -> String {
        s.replacingOccurrences(of: "|", with: "\\|").replacingOccurrences(of: "\n", with: " ")
    }
}
